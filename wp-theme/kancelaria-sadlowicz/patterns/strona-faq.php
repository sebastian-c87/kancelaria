<details class="wp-block-details ks-faq-item"><summary>Czy mogę liczyć na ugodę bez procesu?</summary><!-- wp:paragraph -->
<p>Tak, <strong>zawsze staram się w pierwszej kolejności wypracować ugodę polubowną</strong>, która oszczędza czas, pieniądze i emocje. Ugoda to rozwiązanie korzystne dla obu stron - kończy spór szybciej i taniej niż proces sądowy.</p>
Drogi do ugody:
<!-- /wp:paragraph -->

<!-- wp:list -->
<ul class="wp-block-list"></ul>
