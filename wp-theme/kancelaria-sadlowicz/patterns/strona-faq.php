<details class="wp-block-details ks-faq-item"><summary>Ile kosztuje pierwsza konsultacja?</summary><!-- wp:paragraph -->
<p>Pierwsza konsultacja prawna kosztuje <strong>od 350 zł</strong> i obejmuje:</p>
<!-- /wp:paragraph -->

<!-- wp:list -->
<ul class="wp-block-list"></ul>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p><li>Szczegółową analizę Twojej sytuacji prawnej (60-90 min)</li><li>Przegląd dokumentów i ocenę szans powodzenia</li><li>Przedstawienie możliwych strategii działania</li><li>Wstępną wycenę kosztów prowadzenia sprawy</li><li>Odpowiedzi na wszystkie pytania</li></ul></p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Ważne:</strong> Jeśli zdecydujesz się na stałą współpracę (np. prowadzenie sprawy sądowej, windykację, abonament), koszt pierwszej konsultacji jest <strong>zaliczany na poczet wynagrodzenia</strong>.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Konsultacja online (wideokonferencja) kosztuje tyle samo co spotkanie osobiste w kancelarii.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq-item"} -->
<details class="wp-block-details ks-faq-item"><summary>Jakie są formy rozliczeń (stawka godzinowa, ryczałt, success fee)?</summary><!-- wp:paragraph -->
<p>Oferuję elastyczne formy rozliczeń dostosowane do charakteru sprawy i Twoich możliwości finansowych:</p>
1. Stawka godzinowa
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Kiedy:</strong> Sprawy o nieprzewidywalnym zakresie prac (np. skomplikowane spory gospodarcze, negocjacje długoterminowe)</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Stawka:</strong> 300-500 zł netto/h (w zależności od złożoności)</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Zalety:</strong> Płacisz tylko za faktycznie przepracowany czas</p>
2. Wynagrodzenie ryczałtowe
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Kiedy:</strong> Sprawy o jasno określonym zakresie (np. rozwód bez sporów majątkowych, pozew o zapłatę, umowa handlowa)</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Kwota:</strong> Ustalana indywidualnie (np. 3.000-8.000 zł za kompletną obsługę sprawy)</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Zalety:</strong> Znasz całkowity koszt z góry, bez niespodzianek</p>
3. Success fee (wynagrodzenie od rezultatu)
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Kiedy:</strong> Windykacja należności, sprawy odszkodowawcze</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Wysokość:</strong> 15-25% od odzyskanej kwoty (+ ewentualna minimalna stawka podstawowa)</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Zalety:</strong> Minimalne ryzyko finansowe - płacisz tylko w przypadku sukcesu</p>
4. Abonament prawny (dla firm)
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Kiedy:</strong> Stała obsługa prawna przedsiębiorstwa</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Kwota:</strong> Od 1.000 zł netto/mc</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Zalety:</strong> Nielimitowane konsultacje telefoniczne, priorytetowy kontakt, przewidywalny koszt</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Która forma jest dla mnie najlepsza?</strong> Omówimy to podczas pierwszej konsultacji i wybierzemy najkorzystniejsze rozwiązanie.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq-item"} -->
<details class="wp-block-details ks-faq-item"><summary>Czy mogę uzyskać wycenę przed rozpoczęciem współpracy?</summary><!-- wp:paragraph -->
<p>Tak, zawsze otrzymujesz szczegółową wycenę przed rozpoczęciem współpracy. Po pierwszej konsultacji przygotowuję:</p>
<!-- /wp:paragraph -->

<!-- wp:list -->
<ul class="wp-block-list"></ul>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p><li><strong>Pisemną wycenę</strong> - dokładny kosztorys obejmujący wynagrodzenie adwokata, opłaty sądowe i inne koszty</li><li><strong>Zakres usług</strong> - precyzyjny opis tego, co obejmuje wynagrodzenie</li><li><strong>Harmonogram płatności</strong> - kiedy i ile należy wpłacić (zaliczka, raty, płatność końcowa)</li><li><strong>Warunki współpracy</strong> - zasady rozliczenia, komunikacji i ewentualnej rezygnacji</li></ul></p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Wycena jest <strong>bezpłatna</strong> i nie zobowiązuje Cię do współpracy - masz czas na przemyślenie decyzji. Jeśli wycena Ci nie odpowiada, możemy ją negocjować lub zaproponować inną formę rozliczenia.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq-item"} -->
<details class="wp-block-details ks-faq-item"><summary>Czy są jakieś ukryte koszty?</summary><!-- wp:paragraph -->
<p><strong>Nie - wszystkie koszty są transparentne i znane z góry.</strong> Przed rozpoczęciem współpracy przedstawiam pełny kosztorys obejmujący:</p>
<!-- /wp:paragraph -->

<!-- wp:list -->
<ul class="wp-block-list"></ul>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p><li><strong>Wynagrodzenie adwokata</strong> (stawka godzinowa, ryczałt lub success fee)</li><li><strong>Opłaty sądowe</strong> (wpis od pozwu, opłata skarbowa, koszty doręczeń)</li><li><strong>Koszty dodatkowe</strong> (opinie biegłych, tłumaczenia, wyjazdy poza Warszawę - jeśli dotyczy)</li></ul></p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Jeśli w trakcie sprawy pojawią się <strong>nieprzewidziane koszty</strong> (np. konieczność opinii biegłego), zawsze informuję o tym wcześniej i uzyskuję Twoją zgodę.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Opłaty sądowe</strong> możesz sprawdzić samodzielnie na stronie sądu lub w ustawie o kosztach sądowych w sprawach cywilnych. Zawsze wyjaśniam, ile i za co płacisz.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq-item"} -->
<details class="wp-block-details ks-faq-item"><summary>Jak wygląda rozliczenie w przypadku windykacji należności?</summary><!-- wp:paragraph -->
<p>W sprawach windykacyjnych oferuję najczęściej <strong>success fee</strong> - wynagrodzenie uzależnione od skuteczności windykacji. Dzięki temu minimalizujesz ryzyko finansowe.</p>
Model success fee:
<!-- /wp:paragraph -->

<!-- wp:list -->
<ul class="wp-block-list"></ul>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p><li><strong>Prowizja:</strong> 15-25% od odzyskanej kwoty (% zależy od wysokości należności i stopnia skomplikowania)</li><li><strong>Stawka minimalna (opcjonalnie):</strong> 500-1.000 zł (zabezpieczenie podstawowych czynności, zaliczane na poczet prowizji)</li><li><strong>Płatność:</strong> Dopiero po faktycznym odzyskaniu pieniędzy (nie przy wyroku, ale przy wpłacie od dłużnika)</li></ul>
Przykład:</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Należność: 50.000 zł | Prowizja: 20% | Odzyskana kwota: 50.000 zł<br> <strong>Twoje wynagrodzenie adwokata:</strong> 10.000 zł<br> <strong>Otrzymujesz netto:</strong> 40.000 zł</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Model ryczałtowy:</strong> Możliwy przy mniejszych należnościach (do 10.000 zł) - ustalona kwota 1.500-3.000 zł bez względu na rezultat.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Razem wybieramy optymalny model rozliczenia podczas pierwszej konsultacji.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq-item"} -->
<details class="wp-block-details ks-faq-item"><summary>Czy można rozłożyć płatność na raty?</summary><!-- wp:paragraph -->
<p>Tak, w uzasadnionych przypadkach można rozłożyć płatność na raty. Rozumiem, że sprawy prawne często pojawiają się niespodziewanie i mogą stanowić obciążenie finansowe.</p>
Możliwości rozłożenia płatności:
<!-- /wp:paragraph -->

<!-- wp:list -->
<ul class="wp-block-list"></ul>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p><li><strong>Zaliczka + raty miesięczne</strong> - np. 30% z góry, reszta w 3-6 ratach miesięcznych</li><li><strong>Raty powiązane z etapami sprawy</strong> - np. 1. rata przy złożeniu pozwu, 2. rata przy pierwszej rozprawie, 3. rata przy wyroku</li><li><strong>Odroczona płatność</strong> - w sprawach success fee (windykacja) płacisz dopiero po odzyskaniu pieniędzy</li></ul></p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Warunki rat ustalamy indywidualnie i zapisujemy w umowie o świadczenie pomocy prawnej. Nie naliczam odsetek ani dodatkowych opłat za rozłożenie płatności na raty.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Ważne:</strong> Możliwość rat nie dotyczy opłat sądowych (te muszą być wpłacone jednorazowo przy składaniu pozwu).</p>
