<!-- /wp:list -->

<!-- wp:paragraph -->
<p><li><strong>Sprawy cywilne:</strong> umowy, korespondencja, wezwania do zapłaty, dowody wpłat</li><li><strong>Sprawy rodzinne:</strong> akt małżeństwa, akty urodzenia dzieci, dokumenty dotyczące majątku</li><li><strong>Sprawy pracownicze:</strong> umowa o pracę, wypowiedzenie, korespondencja z pracodawcą</li><li><strong>Windykacja:</strong> faktury, umowy, dowody wysyłki, korespondencja z dłużnikiem</li><li><strong>Sprawy gospodarcze:</strong> dokumenty rejestrowe spółki, umowy handlowe, dokumentacja księgowa</li></ul></p>
