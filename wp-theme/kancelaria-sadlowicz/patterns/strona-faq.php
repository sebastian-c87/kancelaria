<details class="wp-block-details ks-faq-item"><summary>Jak długo trwa sprawa sądowa?</summary><!-- wp:paragraph -->
<p>Czas trwania sprawy zależy od wielu czynników: rodzaju postępowania, obciążenia sądu, złożoności sprawy i postawy drugiej strony. Oto orientacyjne terminy:</p>
Postępowanie upominawcze (elektroniczne):
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>2-4 tygodnie</strong> - najszybsza droga do uzyskania nakazu zapłaty (windykacja należności)</p>
Sprawy cywilne (I instancja):
<!-- /wp:paragraph -->

<!-- wp:list -->
<ul class="wp-block-list"></ul>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p><li><strong>Proste sprawy (zapłata, umowy):</strong> 6-12 miesięcy</li><li><strong>Średniej złożoności:</strong> 12-18 miesięcy</li><li><strong>Skomplikowane (z biegłymi, wieloma stronami):</strong> 18-36 miesięcy</li></ul>
Sprawy rodzinne:</p>
<!-- /wp:paragraph -->

<!-- wp:list -->
<ul class="wp-block-list"></ul>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p><li><strong>Rozwód bez sporów:</strong> 3-6 miesięcy</li><li><strong>Rozwód ze sporami (majątek, dzieci):</strong> 12-24 miesiące</li><li><strong>Alimenty:</strong> 3-8 miesięcy</li></ul>
Apelacja (II instancja):</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>6-12 miesięcy</strong> od złożenia apelacji</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Uwaga:</strong> To terminy orientacyjne - rzeczywisty czas może być krótszy lub dłuższy. Zawsze na bieżąco informuję o przewidywanym czasie trwania Twojej konkretnej sprawy.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

