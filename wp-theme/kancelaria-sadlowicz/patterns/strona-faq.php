<details class="wp-block-details ks-faq-item"><summary>Jak wygląda pierwsza konsultacja?</summary><!-- wp:paragraph -->
<p>Pierwsza konsultacja to spotkanie, podczas którego szczegółowo poznaję Twoją sytuację prawną i oczekiwania. Trwa zwykle 60-90 minut i obejmuje:</p>
<!-- /wp:paragraph -->

<!-- wp:list -->
<ul class="wp-block-list"></ul>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p><li>Analiza Twojej sytuacji i problemów prawnych</li><li>Przegląd posiadanych dokumentów</li><li>Omówienie możliwych strategii działania</li><li>Wstępna ocena szans powodzenia sprawy</li><li>Przedstawienie kosztów i formy rozliczenia</li><li>Odpowiedzi na wszystkie Twoje pytania</li></ul></p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Spotkanie może odbyć się osobiście w kancelarii w Warszawie lub online (wideokonferencja). Po konsultacji otrzymasz pisemną wycenę i propozycję współpracy.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq-item"} -->
<details class="wp-block-details ks-faq-item"><summary>Czy konsultacja może odbyć się online?</summary><!-- wp:paragraph -->
<p>Tak, oferuję pełną obsługę online - konsultacje wideo, wymianę dokumentów przez email i reprezentację zdalną. Dzięki nowoczesnym narzędziom możesz skorzystać z moich usług bez konieczności osobistej wizyty w kancelarii.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Konsultacje online przeprowadzam za pomocą bezpiecznych platform komunikacyjnych (Zoom, Google Meet, Microsoft Teams). Przed spotkaniem wystarczy, że przygotujesz dokumenty w formie skanów/zdjęć i prześlesz je emailem.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p><strong>Obsługa online jest szczególnie wygodna dla:</strong></p>
<!-- /wp:paragraph -->

<!-- wp:list -->
<ul class="wp-block-list"></ul>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p><li>Klientów spoza Warszawy</li><li>Osób pracujących w systemie zmianowym</li><li>Przedsiębiorców z napiętym grafikiem</li><li>Osób z ograniczoną mobilnością</li></ul></p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq-item"} -->
<details class="wp-block-details ks-faq-item"><summary>Jakie dokumenty przygotować na pierwsze spotkanie?</summary><!-- wp:paragraph -->
<p>Aby konsultacja była maksymalnie efektywna, warto przygotować wszystkie dokumenty związane ze sprawą. Nie martw się, jeśli czegoś nie masz - omówimy to wspólnie i poradzimy, jak uzupełnić brakujące materiały.</p>
