<h2 class="wp-block-heading section-title">Najczęściej zadawane pytania <em>o ceny</em></h2>
<!-- /wp:heading -->

<!-- wp:group {"className":"ks-faq"} -->
<div class="wp-block-group ks-faq"><!-- wp:details {"className":"ks-faq-item"} -->
<details class="wp-block-details ks-faq-item"><summary>Dlaczego ceny są podawane w przedziałach?</summary><!-- wp:paragraph -->
<p>Każda sprawa jest inna - wycena zależy od skomplikowania, wartości sporu, ilości dokumentów i przewidywanego czasu pracy. Po wstępnej konsultacji przedstawiam <strong>szczegółową wycenę</strong> z rozbiciem na poszczególne etapy.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq-item"} -->
<details class="wp-block-details ks-faq-item"><summary>Czy można negocjować ceny?</summary><!-- wp:paragraph -->
<p>Tak! W przypadku <strong>długotrwałej współpracy</strong>, <strong>większej liczby spraw</strong> lub <strong>poleceń od obecnych klientów</strong> oferuję rabaty do 20%. Klienci abonamentowi mają gwarantowane rabaty 15-30%.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq-item"} -->
<details class="wp-block-details ks-faq-item"><summary>Czy mogę rozłożyć płatność na raty?</summary><!-- wp:paragraph -->
<p>Tak, w przypadku spraw długotrwałych (rozwody, duże windykacje) możliwa płatność ratalna: <strong>zaliczka 30-50%</strong> + raty miesięczne przez czas trwania sprawy.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq-item"} -->
<details class="wp-block-details ks-faq-item"><summary>Co się stanie jeśli przegram sprawę?</summary><!-- wp:paragraph -->
<p>Wynagrodzenie za reprezentację <strong>nie zależy</strong> od wyniku sprawy (chyba że ustaliliśmy model success fee w windykacji). Jeśli przegrasz, sąd może zasądzić <strong>zwrot kosztów przeciwnika</strong> (jego prawnik + opłaty sądowe). O tym ryzyku informuję <strong>przed</strong> rozpoczęciem sprawy i oceniam szanse powodzenia.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq-item"} -->
<details class="wp-block-details ks-faq-item"><summary>Czy konsultacja jest płatna?</summary><!-- wp:paragraph -->
<p>Pierwsza konsultacja (60 min) - <strong>350-500 zł</strong>. Jeśli zdecydujesz się na dalszą współpracę (reprezentację w sprawie), <strong>zaliczam ją na poczet wynagrodzenia</strong>. Oferuję także <strong>bezpłatną 15-minutową konsultację wstępną</strong> (telefon/online) - sprawdzamy czy mogę Ci pomóc.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq-item"} -->
<details class="wp-block-details ks-faq-item"><summary>Czy abonament można rozwiązać w każdej chwili?</summary><!-- wp:paragraph -->
<p>Tak! Abonament na czas nieokreślony z <strong>1-miesięcznym okresem wypowiedzenia</strong>. Możesz też wybrać abonament na czas określony (6 lub 12 miesięcy) z <strong>rabatem 10-15%</strong>.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq-item"} -->
<details class="wp-block-details ks-faq-item"><summary>Co jeśli wykorzystam wszystkie godziny w pakiecie abonamentowym?</summary><!-- wp:paragraph -->
<p>Możesz dokupić dodatkowe godziny w preferencyjnej stawce (zależnie od pakietu: 220-300 zł netto/h). Alternatywnie - niewykorzystane godziny <strong>przechodzą na następny miesiąc</strong> (max. 2 miesiące wstecz).</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details {"className":"ks-faq-item"} -->
<details class="wp-block-details ks-faq-item"><summary>Czy wynagrodzenie obejmuje koszty sądowe?</summary><!-- wp:paragraph -->
<p><strong>NIE.</strong> Moje wynagrodzenie to koszt obsługi prawnej. Dodatkowo musisz pokryć: opłaty sądowe (600 zł za rozwód, 5% wartości sporu w sprawach cywilnych itd.), opinie biegłych, tłumaczenia. Zawsze informuję o <strong>pełnych kosztach</strong> przed rozpoczęciem sprawy.</p>
